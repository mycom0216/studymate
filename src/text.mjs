// ─────────────────────────────────────────────────────────────────────────────
// text.mjs — 한국어 텍스트 처리 도구(토큰화·문장 분리·개인정보 마스킹)
//
// [토큰(token)이란] 검색을 위해 글을 잘게 쪼갠 "비교 단위". 이 프로젝트는 세 종류를 만듭니다(접두어로 구분).
//     'w:반품'  어절(띄어쓰기 단위)에서 조사를 뗀 어간
//     'b:반품'  어간 안의 연속 두 글자(바이그램, bigram)
//     'c:환'    한 글자짜리 어간
//   예) "반품이 가능한가요" → w:반품, b:반품, w:가능한가요 …  (조사 '이'가 떨어져 "반품"으로 통일)
//   형태소 분석기 같은 무거운 도구 없이도 "반품이/반품은/반품하려면" 처럼 어미가 변한 표현을 서로 매칭하는 것이 목표입니다.
// ─────────────────────────────────────────────────────────────────────────────
// 한국어 질의·문서용 가벼운 토크나이저: 어절 + 어절 내부 문자 바이그램.
// 형태소 분석기 없이도 조사·어미 변화("반품이/반품은/반품하려면")에 견디도록 바이그램을 씁니다.
// 어절 끝에 붙는 대표적인 조사/어미 목록(긴 것을 앞에 둬야 '으로'가 '로'보다 먼저 매칭됨). $ 는 "끝에서" 라는 뜻.
const JOSA = /(으로|에서|에게|까지|부터|이나|이랑|인가요|나요|까요|은|는|이|가|을|를|에|로|의|도|만|과|와|요)$/u;

// 텍스트 정규화: NFKC(전각/호환 문자를 표준 문자로 통일) → 소문자 → 연속 공백을 한 칸으로 → 앞뒤 공백 제거.
// 검색에서 "ABC"와 "abc", 전각 "１２３"과 "123"을 같게 보기 위한 전처리입니다. null/undefined 는 빈 문자열로 처리.
export function normalize(text) {
  return String(text ?? '').normalize('NFKC').toLowerCase().replace(/\s+/gu, ' ').trim();
}

// 글자(\p{L})와 숫자(\p{N})가 이어진 덩어리 = 어절 목록. 구두점은 버려집니다. 하나도 없으면 빈 배열.
export function words(text) {
  return normalize(text).match(/[\p{L}\p{N}]+/gu) ?? [];
}

// 질의 전용: 의미 없는 군말·요청 어미("알려줘", "어때", "되나요")는 검색 근거에서 뺍니다.
// (이런 말은 어느 문서에나 있거나 아예 없어서 "무엇에 대한 질문인지"를 알려 주지 못하기 때문입니다.)
export const FILLER = new Set(['알려줘', '알려주세요', '알려줄래', '해줘', '해주세요', '줄래', '어때', '어떻게', '어떡해', '되나요', '돼요', '있나요', '있어요', '가능한가요', '가능해요', '궁금해요', '궁금합니다', '싶어요', '싶은데', '하나요', '할까요', '인가요', '이에요', '예요', '뭐야', '뭔가요', '무엇인가요', '설명해줘', '설명해주세요', '설명해', '뭐예요', '뭘까요', '무엇', '뭐', '좀', '혹시', '그냥', '정말', '진짜', '너', '나', '저', '제가', '저는', '내가']);

// 어절 끝의 조사를 떼어 낸 어간(2글자 이하는 그대로)
// 2글자 이하는 조사처럼 보이는 끝글자가 사실 단어의 일부일 수 있어("나라"의 '라' 등) 건드리지 않습니다.
export const stem = (w) => (w.length > 2 ? w.replace(JOSA, '') : w);

// 텍스트 → 토큰 배열. query:true 면 질의용으로 군말(FILLER)을 제외합니다.
export function tokens(text, { query = false } = {}) {
  const out = [];
  for (const w of words(text)) {
    // 군말 제외(질의일 때만)
    if (query && FILLER.has(w)) continue;
    // 조사를 뗀 어간(stem).
    const st = stem(w);
    // 어간이 두 글자 이상일 때만 어절 토큰 'w:' 으로 추가(한 글자 어절은 너무 흔해 변별력이 낮음)
    if (st.length >= 2) out.push('w:' + st);
    // [...st] 는 문자열을 "글자 단위"로 쪼갭니다(한글 한 글자를 정확히 한 칸으로).
    const chars = [...st];
    // 한 글자 어간은 바이그램을 못 만드니 'c:' 토큰으로 남깁니다.
    if (chars.length === 1) out.push('c:' + chars[0]);
    // 인접한 두 글자씩 'b:' 토큰 생성: "반품" → b:반품, "반품비" → b:반품, b:품비
    for (let i = 0; i + 1 < chars.length; i++) out.push('b:' + chars[i] + chars[i + 1]);
  }
  return out;
}

// 문장 분리: 마침표/느낌표/물음표 뒤의 공백에서 자릅니다. (?<=[.!?]) 는 "앞에 그 문자가 있을 때"만 매칭하는 lookbehind 라 구두점이 문장에 남습니다.
// 앞뒤 공백을 다듬고 빈 문장은 제거합니다.
export function sentences(text) {
  return String(text).split(/(?<=[.!?])\s+/u).map((s) => s.trim()).filter(Boolean);
}

// 개인정보(전화·이메일·카드·주민번호)를 저장·LLM 전달 전에 가립니다.
// 반환: { masked: 가려진 문장, found: 발견된 개인정보 종류 이름 배열 }
// 한계: 정규식 기반이라 형식이 특이한 번호나 이름·주소는 못 가립니다(README 의 주의 문구 참고).
export function maskPII(text) {
  const found = [];
  let masked = String(text ?? '');
  // [종류, 찾는 정규식, 바꿀 문구]. 순서가 중요합니다: 주민번호(13자리)·카드(16자리)를 전화번호보다 먼저 처리해야
  // 그 숫자 조각이 전화번호로 잘못 잡히지 않습니다. \b 는 단어 경계, g 는 모두 치환, u 는 유니코드.
  const rules = [
    // 주민번호: 생년월일 6자리 + (구분 - 또는 공백 선택) + 성별 숫자(1~4) + 6자리
    ['주민등록번호', /\b\d{6}[- ]?[1-4]\d{6}\b/gu, '[주민번호]'],
    // 카드번호: 4자리 묶음 4개(구분자 - 또는 공백 선택)
    ['카드번호', /\b(?:\d{4}[- ]?){3}\d{4}\b/gu, '[카드번호]'],
    // 전화번호: 0으로 시작(지역번호/010) 1~2자리 + 3~4자리 + 4자리
    ['전화번호', /\b0\d{1,2}[- ]?\d{3,4}[- ]?\d{4}\b/gu, '[전화번호]'],
    // 이메일: 아이디@도메인.최상위
    ['이메일', /[\w.+-]+@[\w-]+(?:\.[\w-]+)+/gu, '[이메일]'],
  ];
  // 규칙을 차례로 적용. 치환 결과가 달라졌을 때만 "이 종류를 가렸다"고 기록합니다.
  for (const [name, re, repl] of rules) {
    const next = masked.replace(re, repl);
    if (next !== masked) { found.push(name); masked = next; }
  }
  return { masked, found };
}
